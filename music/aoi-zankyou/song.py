# ---------------------------------------------------------------- メロディ
# 各フレーズ = 2小節(16)。リズム型 + 音程 + 歌詞 で組み立てる。

def phrase(rhythm, pitches, moras):
    """rhythm: 休符は負数。音符の数 = pitches = moras"""
    out, i = [], 0
    for d in rhythm:
        if d < 0:
            out.append(("", "r", -d))
        else:
            out.append((moras[i], pitches[i], d))
            i += 1
    assert i == len(pitches) == len(moras), (moras, i)
    return out

