    return (phrase(R_C7, P_C1, m(l1)) + phrase(R_C7, P_C2, m(l2)) +
            phrase(R_C8, P_C3, m(l3)) + phrase(R_C6, P_C4, m(l4)) +
            phrase(R_C7, P_C1, m(l5)) + phrase(R_C6, P_C6, m(l6)) +
            phrase(R_C13, P_C7, m(l7)))


