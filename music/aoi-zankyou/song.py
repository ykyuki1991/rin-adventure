def m(s):
    """'こ ご え' -> ['こ','ご','え']"""
    return s.split()


def verse(l1, l2, l3, l4):
    return (phrase(R_A7, P_A1, m(l1)) + phrase(R_A10, P_A2, m(l2)) +
            phrase(R_A7, P_A3, m(l3)) + phrase(R_A10, P_A4, m(l4)))


def pre(l1, l2, l3, l4):
    return (phrase(R_B9, P_B1, m(l1)) + phrase(R_B11, P_B2, m(l2)) +
            phrase(R_B8, P_B3, m(l3)) + phrase(R_B8, P_B4, m(l4)))


