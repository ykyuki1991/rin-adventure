// 桜の木（大きさは s でかわる。s=1.2 のとき、この大きさ）
function sakuraTree() {
  const pink = ['#f9c6d9', '#f4a8c6', '#fbd9e6'];
  const r = rng(3001);
  const out = [path('M-14 0 C-10 -60 -20 -100 -40 -140 M-6 -60 C10 -110 30 -130 50 -150', 'none', st('#7a5236', 22)), path('M-12 0 L-6 -120 L10 -120 L12 0 Z', '#7a5236')];
  for (let i = 0; i < 26; i++) {
    const a = r() * Math.PI * 2, d = Math.sqrt(r()) * 1;
    const x = Math.cos(a) * 110 * d, y = -200 + Math.sin(a) * 80 * d;
    out.push(circ(x, y, 34 + r() * 16, pink[i % 3]));
  }
  for (let i = 0; i < 16; i++) out.push(circ(-90 + r() * 180, -250 + r() * 90, 4 + r() * 4, '#ffffff', { opacity: 0.8 }));
  out.push(...[[60, -150], [-70, -160], [0, -140]].map(([x, y]) => circ(x, y, 26, '#e98fb2', { opacity: 0.5 })));
  return out.join('');
}
